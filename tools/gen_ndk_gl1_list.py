#!/usr/bin/env python3
"""Generates shim/ndk/ndk_gl1_list.inc: the GL entry points graphics_translation
has (GLES_APIENTRY in its gles/api_entries.cpp) beyond OpenGL ES 2.0/3.0
(shim/ndk/ndk_gl_list.inc) and the extensions shim/ndk/ndk_gles.cc maps by
hand: OpenGL ES 1.1 (glMatrixMode, glVertexPointer, ...) and its OES
extensions (glGenFramebuffersOES, ...), as X-macro lines

  GLFN1(ret, name, (params), (args))

for guest code drawing with OpenGL ES 1.1 (old games: Angry Birds 2010's
libangrybirds.so). Usage:

  tools/gen_ndk_gl1_list.py upstream/mods/graphics_translation/gles/api_entries.cpp \\
      shim/ndk/ndk_gl_list.inc shim/ndk/ndk_gles.cc > shim/ndk/ndk_gl1_list.inc
"""
import re
import sys


def main(entries, gl_list, gles_cc):
    known = set(re.findall(r'GLFN\(\d, [^,]+, (gl\w+),', open(gl_list).read()))
    known |= set(re.findall(r'NDK_FN\("(gl\w+)"', open(gles_cc).read()))
    text = open(entries).read()
    out = []
    seen = set()
    for m in re.finditer(r'^GLES_APIENTRY\(([^,]+),\s*(\w+)\s*(?:,(.*?))?\)\s*\{', text, re.S | re.M):
        ret, name, params = m.group(1).strip(), 'gl' + m.group(2), ' '.join((m.group(3) or '').split())
        if name in known or name in seen:
            continue
        seen.add(name)
        if params in ('', 'void'):
            params, args = 'void', ''
        else:
            names = []
            for p in params.split(','):
                n = re.findall(r'(\w+)\s*(?:\[\s*\w*\s*\])?$', p.strip())
                names.append(n[0])
            args = ', '.join(names)
        out.append('GLFN1(%s, %s, (%s), (%s))' % (ret, name, params, args))
    print('// Generated by tools/gen_ndk_gl1_list.py from graphics_translation\'s')
    print('// gles/api_entries.cpp: its entry points beyond OpenGL ES 2.0/3.0 (OpenGL ES')
    print('// 1.1 and OES extensions). GLFN1(ret, name, (params), (args)).')
    print('\n'.join(out))


if __name__ == '__main__':
    main(*sys.argv[1:4])
