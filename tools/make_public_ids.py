#!/usr/bin/env python3
"""Pins framework-res's resource ids to another build's (topic userspace).

Android 6.0's system apps (Settings, SystemUI) come from Google's SDK image
(tools/fetch_system_apks6.sh) and were compiled against that build's
framework-res: they refer to its private resources (com.android.internal.R)
by number. AOSP 6.0.1's framework-res numbers about 1900 of them differently
(strings, ids, bools...), so the apps would get other strings and views. This
writes an aapt resource overlay whose values/public.xml gives every resource
of IDS its number there (and declares the ids, which layouts otherwise only
create with @+id, as aapt wants a public symbol defined). Resources only this
build has get numbers after them.

Usage: make_public_ids.py IDS OUT_DIR
  IDS      "0xID type name" lines (aapt dump resources of the other build's
           framework-res.apk; fetch_system_apks6.sh writes it)
  OUT_DIR  gets values/public-arcwasm.xml (pass it as aapt's first -S, with
           --auto-add-overlay)
"""
import os
import re
import sys


def main(argv):
    ids_file, out_dir = argv[1:3]
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/make_public_ids.py; do not edit. -->',
             '<resources>']
    ids = []
    for line in open(ids_file):
        rid, rtype, name = line.split()
        if rtype.startswith('^'):  # ^attr-private: not declarable, numbered alike
            continue
        if not re.match(r'^[A-Za-z_][A-Za-z0-9_.]*$', name):
            continue  # e.g. id/multi-select: no R field, numbered alike
        lines.append('  <public type="%s" name="%s" id="%s" />' % (rtype, name, rid))
        if rtype == 'id':
            ids.append(name)
    lines += ['  <item type="id" name="%s" />' % name for name in ids]
    lines.append('</resources>')
    os.makedirs(os.path.join(out_dir, 'values'), exist_ok=True)
    with open(os.path.join(out_dir, 'values', 'public-arcwasm.xml'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv)
