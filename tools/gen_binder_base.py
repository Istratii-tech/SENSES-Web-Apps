#!/usr/bin/env python3
"""Generates the base class of a lean binder service (topic "activity").

    gen_binder_base.py CLASSPATH INTERFACE SUPERCLASS PACKAGE.NAME OUT.java [transact]

INTERFACE is a binder interface of the framework (an AIDL one such as
android.content.pm.IPackageManager, or a hand-written one such as
android.app.IActivityManager); SUPERCLASS is what a real service extends
(IPackageManager.Stub, ActivityManagerNative): it brings onTransact, so the
service also works through a real transaction. The generated abstract class
implements every method of INTERFACE (as javap lists them from CLASSPATH)
by throwing arcwasm.server.Unimplemented.call("INTERFACE.method"), so a
service in docs/topics/activity.md overrides exactly what the launch path
uses and anything else fails loudly, naming the method. In the lenient mode
(arcwasm.server.Unimplemented.lenient: the phone-like system with SystemUI
and a home screen, topic userspace) such a method instead logs its name once
and answers as a device without the feature would: nothing, 0 or false, an
empty array or list, or null.

With "transact", queryLocalInterface() returns null: IFoo.Stub.asInterface()
then gives every caller in the wasm process the Proxy, and each call is a
real transaction (arguments and results marshalled through Parcel and
onTransact), as between two processes, instead of a direct Java call that
shares objects between "processes"; arcwasm.server.Trace counts them.
"""
import re
import subprocess
import sys


def split_args(s):
    """Splits "a.B<c.D, e.F>, int[]" at top-level commas."""
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def java_type(t):
    return t.replace('$', '.')


PRIMITIVE_DEFAULTS = {
    'boolean': 'false', 'int': '0', 'long': '0L', 'float': '0f', 'double': '0d',
    'short': '(short) 0', 'byte': '(byte) 0', 'char': '(char) 0',
}


def lenient_default(ret):
    """What the lenient mode answers for a method returning ret (a Java type)."""
    if ret in PRIMITIVE_DEFAULTS:
        return PRIMITIVE_DEFAULTS[ret]
    if ret.endswith('[]'):
        base = ret[:-2]
        dims = '[]'
        while base.endswith('[]'):
            base, dims = base[:-2], dims + '[]'
        base = re.sub(r'<.*>', '', base)
        return 'new %s[0]%s' % (base, dims[2:])
    raw = re.sub(r'<.*>', '', ret)
    if raw in ('java.util.List', 'java.util.Collection', 'java.util.ArrayList'):
        return 'new java.util.ArrayList()'
    if raw in ('java.util.Map', 'java.util.HashMap'):
        return 'new java.util.HashMap()'
    if raw == 'android.content.pm.ParceledListSlice':
        return 'new android.content.pm.ParceledListSlice(new java.util.ArrayList())'
    return 'null'


def main():
    classpath, iface, superclass, qualified, out = sys.argv[1:6]
    transact = sys.argv[6:] == ['transact']
    pkg, name = qualified.rsplit('.', 1)
    text = subprocess.run(['javap', '-cp', classpath, iface], check=True,
                          capture_output=True, text=True).stdout
    method = re.compile(r'^\s*public abstract (.+?) (\w+)\((.*)\)( throws [\w.$, ]+)?;$')
    simple = iface.rsplit('.', 1)[1].replace('$', '.')
    lines = []
    for line in text.splitlines():
        m = method.match(line)
        if not m:
            continue
        ret, mname, args, throws = m.groups()
        params = ', '.join('%s p%d' % (java_type(a), i)
                           for i, a in enumerate(split_args(args)))
        jret = java_type(ret)
        lenient = ('return;' if jret == 'void'
                   else 'return %s;' % lenient_default(jret))
        lines.append('    @Override\n    public %s %s(%s)%s {\n'
                     '        if (arcwasm.server.Unimplemented.lenient("%s.%s")) %s\n'
                     '        throw arcwasm.server.Unimplemented.call("%s.%s");\n    }\n'
                     % (jret, mname, params, java_type(throws or ''),
                        simple, mname, lenient, simple, mname))
    if not lines:
        sys.exit('gen_binder_base.py: no methods in %s' % iface)
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_binder_base.py from %s; do not edit.\n' % iface)
        f.write('package %s;\n\n' % pkg)
        f.write('/** Every method of %s, unimplemented: a lean service overrides what it serves. */\n'
                % iface)
        f.write('public abstract class %s extends %s {\n' % (name, java_type(superclass)))
        if transact:
            f.write('    /** Callers get the Proxy: every call is a transaction through Parcel. */\n'
                    '    @Override\n'
                    '    public android.os.IInterface queryLocalInterface(String descriptor) {\n'
                    '        return null;\n    }\n\n'
                    '    @Override\n'
                    '    public boolean onTransact(int code, android.os.Parcel data, '
                    'android.os.Parcel reply, int flags)\n'
                    '            throws android.os.RemoteException {\n'
                    '        arcwasm.server.Trace.call(%s.class, %s.class, code);\n'
                    '        return super.onTransact(code, data, reply, flags);\n    }\n\n'
                    % (java_type(iface), java_type(superclass)))
        f.write('\n'.join(lines))
        f.write('}\n')


if __name__ == '__main__':
    main()
