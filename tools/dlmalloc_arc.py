#!/usr/bin/env python3
"""Emscripten's dlmalloc with a record of the memory it never handed out
(topic wasm-heap-trim, docs/topics/wasm-heap-trim.md); shim/memory/
dlmalloc_report.c includes the result in place of dlmalloc.c.

An iPhone counts a page of the wasm memory in the tab's footprint from its
first touch on -- a read too -- and for good. dlmalloc's top chunk moves up
only into memory nothing has touched: above the highest place the top has
been (plus its header) is untouched zeros, and calloc need not write zeros
there (writing them would make that memory count). The hooks:

  ARC_TOP_MOVED(p)      the top chunk now starts at p (init_top, the first
                        chunk of a segment, realloc extending into the top)
  ARC_TOP_FOOT(p, n)    init_top is about to write a fake chunk's head at
                        the end of the top (p, n bytes): the last such head,
                        if now inside the top, is zeroed again
  ARC_TOP_CARVED(c, t)  chunk c was cut off the top's start; the top now
                        starts at t
  ARC_FRESH_RESET()     before calloc's allocation (the record of a cut is
                        this thread's, of this allocation)
  ARC_CLEAR(mem, n)     calloc's zeros, but where the memory is untouched
  ARC_MALLOC_ENTER(n)   malloc of n bytes begins (diagnostics)

Usage: dlmalloc_arc.py EMSCRIPTEN_DLMALLOC_C OUT_C
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()


def sub(pattern, repl, count, flags=0):
    """Replaces |pattern| (a regex) by |repl|; it must occur |count| times."""
    global text
    text, n = re.subn(pattern, repl, text, flags=flags)
    if n != count:
        sys.exit('dlmalloc_arc.py: %r found %d times, expected %d (another Emscripten dlmalloc?)'
                 % (pattern, n, count))


# init_top: the top chunk of a (new or grown) segment, and the fake chunk
# head it writes at the top's end (inside the top once the segment grows:
# ARC_TOP_FOOT clears the last one when it is).
sub(r'(\n    m->top = p;\n    m->topsize = psize;\n    p->head = psize \| PINUSE_BIT;\n)',
    r'\1    ARC_TOP_MOVED(p);\n', 1)
sub(r'(\n    chunk_plus_offset\(p, psize\)->head = TOP_FOOT_SIZE;\n)',
    r'\n    ARC_TOP_FOOT(p, psize);\1', 1)
# prepend_alloc: the rest of new memory before the old base joins the top.
sub(r'(\n        m->top = q;\n        q->head = tsize \| PINUSE_BIT;\n)',
    r'\1        ARC_TOP_MOVED(q);\n', 1)
# A chunk cut off the top: sys_alloc, dlmalloc, mspace_malloc.
sub(r'(mchunkptr r = (?:m|gm|ms)->top = chunk_plus_offset\(p, nb\);)',
    r'\1 ARC_TOP_CARVED(p, r);', 3)
# try_realloc_chunk: a chunk extended into the top.
sub(r'(\n                m->top = newtop;\n                m->topsize = newtopsize;\n)',
    r'\1                ARC_TOP_MOVED(newtop);\n', 1)
# Diagnostics: each malloc's size on entry (ARC_MALLOC_ENTER, dlmalloc_report.c).
sub(r'(\nvoid\* dlmalloc\(size_t bytes\) \{\n)', r'\1    ARC_MALLOC_ENTER(bytes);\n', 1)
# calloc: zeros only where the memory may have been touched.
sub(r'\n    mem = dlmalloc\(req\);\n    if \(mem != 0 && calloc_must_clear\(mem2chunk\(mem\)\)\)\n'
    r'        memset\(mem, 0, req\);\n',
    '\n    ARC_FRESH_RESET();\n    mem = dlmalloc(req);\n'
    '    if (mem != 0 && calloc_must_clear(mem2chunk(mem)))\n        ARC_CLEAR(mem, req);\n', 1)

open(out, 'w').write('/* Generated by tools/dlmalloc_arc.py from %s */\n' % src + text)
