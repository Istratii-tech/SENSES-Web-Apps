#!/usr/bin/env python3
"""Writes shim/fw6-hwui/hwui_gl_names.h: the renames that put hwui on its
own GL and EGL in WebAssembly (topic fw6-hwui, docs/topics/fw6-hwui.md;
the same header serves hwui 8.1, topic fw8-graphics).

  glXxx  (GLES 2.0/3.0 core)  -> emscripten_glXxx (Emscripten's WebGL2)
  glXxx  (hooked: framebuffer 0, version, client arrays; extensions)
                              -> arc_hwui_glXxx   (shim/fw6-hwui/hwui_{egl,gl}.cc)
  eglXxx (all)                -> arc_hwui_eglXxx  (shim/fw6-hwui/hwui_egl.cc)

so that hwui renders through a WebGL2 context of its RenderThread whatever
other GL/EGL the program links (graphics_translation defines glXxx/eglXxx).

Usage: gen_hwui_gl_names.py AOSP60_DIR > shim/fw6-hwui/hwui_gl_names.h
"""
import re
import sys

# GL calls hwui makes that need more than Emscripten's function: the
# window's framebuffer 0 is an FBO, the version and extensions hwui sees.
HOOKED = ['glBindFramebuffer', 'glDeleteFramebuffers', 'glGetString',
          # GLES 3 calls of hwui's pixel buffer objects, which it uses only on
          # GLES 3 (it is told 2.0); Emscripten has them only with FULL_ES3.
          'glMapBufferRange', 'glUnmapBuffer',
          # client-side vertex and index arrays (shim/fw6-hwui/hwui_gl.cc)
          'glBindBuffer', 'glBufferData', 'glBufferSubData', 'glDeleteBuffers',
          'glVertexAttribPointer', 'glEnableVertexAttribArray',
          'glDisableVertexAttribArray', 'glDrawArrays', 'glDrawElements',
          # external textures (TextureView, SurfaceTexture: GL_TEXTURE_EXTERNAL_OES)
          # as 2D textures, samplerExternalOES as sampler2D (topic fw8-graphics)
          'glBindTexture', 'glTexParameteri', 'glTexImage2D', 'glShaderSource']
# Extensions hwui calls (only when advertised; none is, except as noted).
EXTENSIONS = ['glDiscardFramebufferEXT', 'glEGLImageTargetTexture2DOES', 'glStartTilingQCOM',
              'glEndTilingQCOM', 'glInsertEventMarkerEXT', 'glPushGroupMarkerEXT',
              'glPopGroupMarkerEXT']
EGL_EXTRA = ['eglCreateImageKHR', 'eglDestroyImageKHR', 'eglCreateSyncKHR', 'eglDestroySyncKHR',
             'eglClientWaitSyncKHR', 'eglSwapBuffersWithDamageKHR', 'eglBeginFrame',
             # hwui 8.1 (topic fw8-graphics): EGL_KHR_partial_update, when advertised
             'eglSetDamageRegionKHR']


def names(path, pattern):
    return sorted(set(re.findall(pattern, open(path).read())))


def main(aosp):
    inc = aosp + '/frameworks/native/opengl/include'
    gl = names(inc + '/GLES2/gl2.h', r'GL_APIENTRY (gl\w+)') + \
        names(inc + '/GLES3/gl3.h', r'GL_APIENTRY (gl\w+)')
    egl = names(inc + '/EGL/egl.h', r'EGLAPIENTRY (egl\w+)') + EGL_EXTRA
    out = ['// Generated by tools/gen_hwui_gl_names.py; do not edit.',
           '// hwui on its own GL (Emscripten WebGL2) and EGL (shim/fw6-hwui).',
           '#ifndef ARC_WASM_HWUI_GL_NAMES_H_', '#define ARC_WASM_HWUI_GL_NAMES_H_', '']
    for n in sorted(set(gl)):
        target = 'arc_hwui_' + n if n in HOOKED else 'emscripten_' + n
        out.append('#define %s %s' % (n, target))
    for n in EXTENSIONS:
        out.append('#define %s arc_hwui_%s' % (n, n))
    for n in sorted(set(egl)):
        out.append('#define %s arc_hwui_%s' % (n, n))
    out += ['', '#endif  // ARC_WASM_HWUI_GL_NAMES_H_', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
