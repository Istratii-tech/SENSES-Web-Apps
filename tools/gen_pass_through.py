#!/usr/bin/env python3
"""Generates shim/graphics_translation/gles/pass_through.h.

ARC generated this header from Pepper's PPB_OpenGLES2 IDL: PASS_THROUGH(ctx,
Name, args...) called NameCall(ctx, args...), which forwarded to the browser
through Pepper. In the wasm port the "browser GL" is Emscripten's WebGL
binding. ARC itself defines glName (its GLES implementation for apps), so the
host functions are reached through Emscripten's emscripten_glName aliases.

Usage: gen_pass_through.py GL2_H SOURCE_DIR OUTPUT
"""
import re
import sys

gl2_h, src_dir, out = sys.argv[1:4]
import glob
names = set()
for path in glob.glob(src_dir + '/**/*.cpp', recursive=True) + glob.glob(
        src_dir + '/**/*.h', recursive=True):
    for m in re.finditer(r'PASS_THROUGH\(\s*[^,]+,\s*([A-Za-z0-9]+)',
                         open(path).read()):
        names.add(m.group(1))

protos = {}
for m in re.finditer(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+gl(\w+)\s*\(([^;]*)\);',
                     open(gl2_h).read()):
    protos[m.group(2)] = (m.group(1), m.group(3))

special = {'MapTexSubImage2DCHROMIUM', 'UnmapTexSubImage2DCHROMIUM'}
missing = sorted(n for n in names if n not in protos and n not in special)
if missing:
    sys.exit('no prototype for: ' + ', '.join(missing))

lines = ['// AUTOGENERATED by tools/gen_pass_through.py. DO NOT EDIT.',
         '#ifndef GRAPHICS_TRANSLATION_GLES_PASS_THROUGH_H_',
         '#define GRAPHICS_TRANSLATION_GLES_PASS_THROUGH_H_', '',
         '#include <GLES2/gl2.h>', '',
         'class GlesContext;', '',
         '// Each call names the GlesContext whose host context it targets (under',
         '// Pepper, a Graphics3D resource). All host contexts are virtual contexts',
         '// on one WebGL2 context; this switches to the right one first.',
         'void ArcWasmUseGlesContext(const GlesContext* context);', '',
         '#define PASS_THROUGH(_context, _name, ...) \\',
         '    (ArcWasmUseGlesContext(_context), emscripten_gl##_name(__VA_ARGS__))',
         '', 'extern "C" {']
for n in sorted(names):
    if n in special:
        continue
    ret, args = protos[n]
    lines.append('%s emscripten_gl%s(%s);' % (ret, n, args))
lines += ['}  // extern "C"', '',
          '// CHROMIUM_map_sub has no WebGL equivalent; emulated in',
          '// native_webgl.cpp with a staging buffer and glTexSubImage2D.',
          'void* emscripten_glMapTexSubImage2DCHROMIUM(',
          '    GLenum target, GLint level, GLint xoffset, GLint yoffset,',
          '    GLsizei width, GLsizei height, GLenum format, GLenum type,',
          '    GLenum access);',
          'void emscripten_glUnmapTexSubImage2DCHROMIUM(const void* mem);', '',
          '#endif  // GRAPHICS_TRANSLATION_GLES_PASS_THROUGH_H_', '']
open(out, 'w').write('\n'.join(lines))
print('%d functions' % len(names))

