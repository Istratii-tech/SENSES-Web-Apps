#!/usr/bin/env python3
"""Generates shim/ndk/ndk_gl_list.inc: every OpenGL ES 3.0 entry point
(GLES3/gl3.h of the NDK, android-18) as an X-macro line

  GLFN(es, ret, name, (params), (args))

es is 2 for the OpenGL ES 2.0 functions (graphics_translation has them),
3 for the ones OpenGL ES 3.0 added. Usage:

  tools/gen_ndk_gl_list.py NDK_ARCHIVE > shim/ndk/ndk_gl_list.inc
"""
import re
import sys
import tarfile

GL3 = '9/platforms/android-18/arch-arm/usr/include/GLES3/gl3.h'
GL2 = '9/platforms/android-18/arch-arm/usr/include/GLES2/gl2.h'


def functions(text):
    out = []
    for m in re.finditer(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);', text, re.S):
        ret, name, params = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
        if params in ('void', ''):
            params, args = 'void', ''
        else:
            names = []
            for p in params.split(','):
                n = re.findall(r'(\w+)\s*(?:\[\s*\w*\s*\])?$', p.strip())
                names.append(n[0])
            args = ', '.join(names)
        out.append((ret, name, params, args))
    return out


def main():
    with tarfile.open(sys.argv[1]) as t:
        gl3 = t.extractfile(GL3).read().decode()
        gl2 = t.extractfile(GL2).read().decode()
    es2 = {f[1] for f in functions(gl2)}
    print('// Generated by tools/gen_ndk_gl_list.py from the NDK\'s GLES3/gl3.h (android-18).')
    print('// GLFN(es, ret, name, (params), (args)): es 2 = OpenGL ES 2.0, 3 = added in 3.0.')
    for ret, name, params, args in functions(gl3):
        print('GLFN(%d, %s, %s, (%s), (%s))' % (2 if name in es2 else 3, ret, name, params, args))


if __name__ == '__main__':
    main()
