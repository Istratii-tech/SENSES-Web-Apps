#!/usr/bin/env python3
"""Generates shim/ndk/ndk_sles_iids.inc: the OpenSL ES interface IDs of
Android's implementation (frameworks/wilhelm, AOSP 6.0.1) as X-macro lines

  IID(name, time_low, time_mid, time_hi_and_version, clock_seq, b0, ..., b5)

The values are SL_IID_array (src/OpenSLES_IID.c) in MPH order (src/MPH.h);
the names come from src/sl_iid.c (SL_IID_X = &SL_IID_array[MPH_Y]).
Usage: tools/gen_ndk_sles_iids.py WILHELM_ARCHIVE > shim/ndk/ndk_sles_iids.inc
"""
import re
import sys
import tarfile


def main():
    with tarfile.open(sys.argv[1]) as t:
        read = lambda p: t.extractfile(p).read().decode()
        array, mph, names = read('src/OpenSLES_IID.c'), read('src/MPH.h'), read('src/sl_iid.c')
    index = {m.group(1): int(m.group(2))
             for m in re.finditer(r'#define\s+(MPH_\w+)\s+(\d+)', mph)}
    body = array[array.index('SL_IID_array[MPH_MAX]'):]
    entries = re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,'
                         r'\s*(0x[0-9a-fA-F]+)\s*,\s*\{([^}]*)\}\s*\}', body)
    print('// Generated by tools/gen_ndk_sles_iids.py from frameworks/wilhelm (AOSP 6.0.1):')
    print('// IID(name, time_low, time_mid, time_hi, clock_seq, node[6]).')
    for m in re.finditer(r'const SLInterfaceID\s+(SL_IID_\w+)\s*=\s*&SL_IID_array\[(MPH_\w+)\]', names):
        e = entries[index[m.group(2)]]
        node = ', '.join(x.strip() for x in e[4].split(','))
        print('IID(%s, %s, %s, %s, %s, %s)' % (m.group(1), e[0], e[1], e[2], e[3], node))


if __name__ == '__main__':
    main()
