#!/usr/bin/env python3
"""Link-time stand-ins of the NDK's arm64 system libraries (topic ndk-arm64).

The NDK is not installed: arm64 test libraries are compiled against AOSP
8.1's bionic headers and linked (lld --no-undefined) against these stubs,
one assembly file per library with every symbol the NDK's API 21+ exports
for arm64 (tests/ndk/android81-ndk-symbols.txt, column API-ARM64). Only
their names and sonames matter: at run time the bridge's host symbols
stand in (shim/ndk, the ELF64 loader). Names of capitals only are data
(SL_IID_*, AMEDIAFORMAT_KEY_*: 8-byte pointer variables), the rest
functions.

    gen_stub_libs.py SYMBOLS OUTDIR LIB...    # writes OUTDIR/LIB.S

With --arm, the same for armeabi-v7a (topic relocs32: test libraries built
like new NDK builds): column API-ARM, 4-byte data. --add LIB:SYMBOL adds a
function the table lacks (e.g. libc.so:__tls_get_addr, Android 10).
"""
import sys


def main():
    args = sys.argv[1:]
    arm = "--arm" in args
    if arm:
        args.remove("--arm")
    extra = {}
    while "--add" in args:
        i = args.index("--add")
        lib, sym = args[i + 1].split(":")
        extra.setdefault(lib, []).append(sym)
        del args[i:i + 2]
    symbols, outdir, libs = args[0], args[1], args[2:]
    by_lib = {lib: list(extra.get(lib, [])) for lib in libs}
    for line in open(symbols):
        if line.startswith("#") or not line.strip():
            continue
        name, lib, api32, api64 = line.split()[:4]
        if lib in by_lib and (api32 if arm else api64).isdigit():
            by_lib[lib].append(name)
    ret, word, size = ("bx lr", ".word", 4) if arm else ("ret", ".quad", 8)
    for lib, names in by_lib.items():
        with open("%s/%s.S" % (outdir, lib), "w") as f:
            f.write("// Generated by tools/ndk64/gen_stub_libs.py: link-time stubs of %s.\n" % lib)
            f.write(".text\n")
            for n in sorted(set(names)):
                if not n.isupper():
                    f.write(".globl %s\n.type %s,%%function\n%s:\n  %s\n" % (n, n, n, ret))
            f.write(".data\n.balign %d\n" % size)
            for n in sorted(set(names)):
                if n.isupper():
                    f.write(".globl %s\n.type %s,%%object\n.size %s,%d\n%s:\n  %s 0\n" % (n, n, n, size, n, word))


if __name__ == "__main__":
    main()
