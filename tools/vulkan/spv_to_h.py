#!/usr/bin/env python3
"""Assembles tests/vulkan/*.spvasm with SPIRV-Tools' spirv-as and writes
tests/vulkan/vktest_spirv.h (C arrays of the words), which is in git so
that the test library builds without SPIRV-Tools (topic vulkan).

  spv_to_h.py SPIRV_AS OUT.h NAME=FILE.spvasm...
"""
import os
import subprocess
import sys
import tempfile

spirv_as, out = sys.argv[1], sys.argv[2]
parts = ['// Generated by tools/vulkan/spv_to_h.py from tests/vulkan/*.spvasm: do not edit.',
         '#include <stdint.h>', '']
for arg in sys.argv[3:]:
    name, path = arg.split('=', 1)
    with tempfile.TemporaryDirectory() as d:
        spv = os.path.join(d, 'out.spv')
        subprocess.check_call([spirv_as, '--target-env', 'spv1.0', path, '-o', spv])
        data = open(spv, 'rb').read()
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    parts.append('// %s' % os.path.basename(path))
    parts.append('static const uint32_t %s[] = {' % name)
    for i in range(0, len(words), 6):
        parts.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 6]) + ',')
    parts.append('};')
    parts.append('')
open(out, 'w').write('\n'.join(parts))
