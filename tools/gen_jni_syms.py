#!/usr/bin/env python3
"""Symbol tables for JNI libraries linked statically into artvm8.

ART finds a native method it has no registered code for by its JNI name
(Java_pkg_Class_method) with dlsym in the libraries System.loadLibrary
opened. In arc-wasm the libraries are linked into the program (no dynamic
loading), so the names are looked up in tables generated here
(shim/art8/static_jni_libs_art8.cc). A table is built inside a wrapper that
includes the C file, so each function's address is taken with its real
type (WebAssembly checks function types).

  gen_jni_syms.py wrapper SOURCE.c OUT.c TABLE   wrapper of SOURCE.c defining
                                                 TABLE (null-terminated)
  gen_jni_syms.py index LIB OUT.c TABLE...       LIB's list of the tables:
                                                 arc_wasm_<LIB>_jni_syms
  gen_jni_syms.py filter SOURCE.c...             prints those that define
                                                 Java_* functions
"""
import re
import sys

DEFINITION = r'\b(Java_[A-Za-z0-9_]+)\s*\(([^;{}]*)\)\s*\{'


def java_functions(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    # Comments out of the way (a commented-out definition is not one).
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    names = []
    for m in re.finditer(DEFINITION, text):
        if m.group(1) not in names:
            names.append(m.group(1))
    return names


def main(argv):
    mode = argv[0]
    if mode == 'filter':
        print(' '.join(f for f in argv[1:] if java_functions(f)))
        return
    if mode == 'wrapper':
        src, out, table = argv[1:4]
        names = java_functions(src)
        with open(out, 'w') as f:
            f.write('// Generated by tools/gen_jni_syms.py: %s and its Java_* functions.\n' % src)
            f.write('#include "%s"\n\n' % src)
            f.write('#include "shim/art8/jni_syms.h"\n\n')
            f.write('const struct ArcWasmJniSym %s[] = {\n' % table)
            for n in names:
                f.write('  {"%s", (void*)%s},\n' % (n, n))
            f.write('  {0, 0},\n};\n')
        return
    if mode == 'index':
        lib, out = argv[1:3]
        tables = argv[3:]
        with open(out, 'w') as f:
            f.write('// Generated by tools/gen_jni_syms.py: the Java_* tables of %s.\n' % lib)
            f.write('#include "shim/art8/jni_syms.h"\n\n')
            for t in tables:
                f.write('extern const struct ArcWasmJniSym %s[];\n' % t)
            f.write('\nconst struct ArcWasmJniSym* const arc_wasm_%s_jni_syms[] = {\n' % lib)
            for t in tables:
                f.write('  %s,\n' % t)
            f.write('  0,\n};\n')
        return
    raise SystemExit(__doc__)


if __name__ == '__main__':
    main(sys.argv[1:])
