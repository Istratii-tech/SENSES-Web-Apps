package arcwasm;

import android.content.res.AssetManager;
import android.content.res.Configuration;
import android.content.res.Resources;
import android.content.res.XmlResourceParser;
import android.util.DisplayMetrics;
import android.util.TypedValue;

import org.xmlpull.v1.XmlPullParser;

import java.io.File;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.Locale;

/**
 * The framework resources (/system/framework/framework-res.apk, AOSP's
 * frameworks/base/core/res built by aapt -x, package 0x01): the system
 * AssetManager and Resources.getSystem(), @android: references from the test
 * APK's resources, and a framework theme (Theme.Holo.Light) resolved through
 * an app style's parent chain, and the R classes in framework.jar
 * (android.R, com.android.internal.R, generated by the same aapt run) against
 * the apk's table. Prints one line per check and exits with the number of
 * failures. Runs on both stacks: Android 4.4.4 (Dalvik) and 6.0.1 (ART);
 * the few differences are by Build.VERSION.SDK_INT.
 */
public class FrameworkResTest {
    private static final String FRAMEWORK_RES = "/system/framework/framework-res.apk";
    private static final String APK = "/system/app/ArcWasmTestApp.apk";
    private static final String PKG = "org.arcwasm.testapp";

    private static final boolean SDK23 = android.os.Build.VERSION.SDK_INT >= 23;
    private static final boolean SDK27 = android.os.Build.VERSION.SDK_INT >= 27;
    private static final boolean SDK29 = android.os.Build.VERSION.SDK_INT >= 29;

    private static int passed;
    private static int failed;

    interface Check {
        void run() throws Exception;
    }

    private static void check(String name, Check c) {
        try {
            c.run();
            passed++;
            System.out.println("[ OK ] " + name);
        } catch (Throwable t) {
            failed++;
            System.out.println("[FAIL] " + name + ": " + t);
            t.printStackTrace(System.out);
        }
    }

    private static void expect(boolean ok, String what) {
        if (!ok) throw new AssertionError(what);
    }

    /**
     * Whether framework-res is numbered as the Android 6.0 image's (topic
     * userspace, tools/make_public_ids.py): a private id is public then.
     */
    private static boolean pinnedIds() {
        try {
            android.R.id.class.getField("seekbar");
            return true;
        } catch (NoSuchFieldException e) {
            return false;
        }
    }

    private static void expectEq(Object expected, Object actual) {
        if (expected == null ? actual != null : !expected.equals(actual)) {
            throw new AssertionError("expected <" + expected + "> but was <" + actual + ">");
        }
    }

    private static Resources newResources(AssetManager am) {
        Configuration config = new Configuration();
        config.setToDefaults();
        config.locale = Locale.US;
        DisplayMetrics metrics = new DisplayMetrics();
        metrics.setToDefaults();
        return new Resources(am, metrics, config);
    }

    /** Theme natives of AssetManager are package-private (Resources.Theme uses them). */
    private static Method method(String name, Class<?>... types) throws Exception {
        Method m = AssetManager.class.getDeclaredMethod(name, types);
        m.setAccessible(true);
        return m;
    }

    /**
     * The path of the APK at |cookie| of |am|: getCookieName() up to 8.1;
     * Android 9 dropped it with AssetManager2 (the path of ApkAssets
     * cookie - 1 then). Through reflection: the source compiles against
     * every framework.
     */
    static String cookieName(AssetManager am, int cookie) throws Exception {
        try {
            return (String) AssetManager.class.getMethod("getCookieName", int.class).invoke(am, cookie);
        } catch (NoSuchMethodException e) {
            Object[] apks = (Object[]) AssetManager.class.getMethod("getApkAssets").invoke(am);
            Object apk = apks[cookie - 1];
            return (String) apk.getClass().getMethod("getAssetPath").invoke(apk);
        }
    }

    public static void main(String[] args) throws Exception {
        final long start = System.nanoTime();
        final AssetManager[] app = new AssetManager[1];
        final Resources[] appRes = new Resources[1];

        check("framework-res.apk: in /system/framework", new Check() {
            public void run() throws Exception {
                expect(new File(FRAMEWORK_RES).isFile(), FRAMEWORK_RES + " missing");
            }
        });

        check("system AssetManager: framework-res.apk is cookie 1", new Check() {
            public void run() throws Exception {
                expectEq(FRAMEWORK_RES, cookieName(AssetManager.getSystem(), 1));
            }
        });

        check("Resources.getSystem(): android strings by id and by name", new Check() {
            public void run() throws Exception {
                Resources sys = Resources.getSystem();
                expectEq("OK", sys.getString(android.R.string.ok));
                expectEq("Cancel", sys.getText(android.R.string.cancel).toString());
                expectEq(Integer.valueOf(android.R.string.ok),
                         Integer.valueOf(sys.getIdentifier("ok", "string", "android")));
                expectEq(Integer.valueOf(android.R.string.ok),
                         Integer.valueOf(sys.getIdentifier("android:string/ok", null, null)));
                expectEq("android:string/ok", sys.getResourceName(android.R.string.ok));
                expectEq("android", sys.getResourcePackageName(android.R.string.ok));
            }
        });

        check("Resources.getSystem(): integer, color, dimension", new Check() {
            public void run() throws Exception {
                Resources sys = Resources.getSystem();
                expectEq(Integer.valueOf(200),
                         Integer.valueOf(sys.getInteger(android.R.integer.config_shortAnimTime)));
                expectEq(Integer.valueOf(0xff000000),
                         Integer.valueOf(sys.getColor(android.R.color.black)));
                TypedValue v = new TypedValue();
                sys.getValue(android.R.dimen.app_icon_size, v, true);
                expectEq(Integer.valueOf(TypedValue.TYPE_DIMENSION), Integer.valueOf(v.type));
                expectEq(Integer.valueOf(TypedValue.COMPLEX_UNIT_DIP),
                         Integer.valueOf((v.data >> TypedValue.COMPLEX_UNIT_SHIFT)
                                         & TypedValue.COMPLEX_UNIT_MASK));
                expectEq(Float.valueOf(48f), Float.valueOf(TypedValue.complexToFloat(v.data)));
            }
        });

        check("Resources.getSystem(): framework layout XML (simple_list_item_1)", new Check() {
            public void run() throws Exception {
                XmlResourceParser p =
                        Resources.getSystem().getLayout(android.R.layout.simple_list_item_1);
                int type;
                while ((type = p.next()) != XmlPullParser.START_TAG) {
                    expect(type != XmlPullParser.END_DOCUMENT, "no start tag");
                }
                expectEq("TextView", p.getName());
                expectEq(Integer.valueOf(android.R.id.text1),
                         Integer.valueOf(p.getAttributeResourceValue(
                                 "http://schemas.android.com/apk/res/android", "id", 0)));
                boolean width = false;
                for (int i = 0; i < p.getAttributeCount(); i++) {
                    if (p.getAttributeNameResource(i) == android.R.attr.layout_width) {
                        expectEq(Integer.valueOf(-1), Integer.valueOf(p.getAttributeIntValue(i, 0)));
                        width = true;
                    }
                }
                expect(width, "no layout_width");
                p.close();
            }
        });

        check("app AssetManager: framework first (cookie 1), then the APK", new Check() {
            public void run() throws Exception {
                AssetManager am = new AssetManager();
                int cookie = am.addAssetPath(APK);
                expect(cookie > 1, "APK cookie " + cookie);
                expectEq(FRAMEWORK_RES, cookieName(am, 1));
                app[0] = am;
                appRes[0] = newResources(am);
            }
        });

        check("app resources: @android: references resolve", new Check() {
            public void run() throws Exception {
                Resources res = appRes[0];
                expectEq("OK", res.getString(res.getIdentifier("ok_label", "string", PKG)));
                expectEq(Integer.valueOf(0xff000000),
                         Integer.valueOf(res.getColor(res.getIdentifier("system_black", "color", PKG))));
                expectEq(Integer.valueOf(48), Integer.valueOf(res.getDimensionPixelSize(
                        res.getIdentifier("icon_size", "dimen", PKG))));
                // The framework is reachable through the app's Resources too.
                expectEq("OK", res.getString(android.R.string.ok));
            }
        });

        check("framework styles: app theme with parent Theme.Holo.Light", new Check() {
            public void run() throws Exception {
                Method createTheme = method("createTheme");
                // A theme handle is an int on 4.4, a long since 5.0.
                Class<?> handle = createTheme.getReturnType();
                Method releaseTheme = method("releaseTheme", handle);
                // Android 9 (AssetManager2): instance methods of other names,
                // and the value lookup returns a boolean.
                final boolean am2 = android.os.Build.VERSION.SDK_INT >= 28;
                final Method applyThemeStyle = am2
                        ? method("applyStyleToTheme", handle, int.class, boolean.class)
                        : method("applyThemeStyle", handle, int.class, boolean.class);
                final Method loadAttr = am2
                        ? method("getThemeValue", handle, int.class, TypedValue.class, boolean.class)
                        : method("loadThemeAttributeValue", handle, int.class, TypedValue.class,
                                 boolean.class);
                final AssetManager am = app[0];
                // loadThemeAttributeValue(theme, attr, value, resolve) >= 0
                class Lookup {
                    boolean found(Object theme, int attr, TypedValue v) throws Exception {
                        Object r = loadAttr.invoke(am2 ? am : null, theme, attr, v, true);
                        return am2 ? (Boolean) r : (Integer) r >= 0;
                    }
                }
                Lookup lookup = new Lookup();
                int appTheme = appRes[0].getIdentifier("AppTheme", "style", PKG);
                expect((appTheme >>> 24) == 0x7f, "AppTheme id " + Integer.toHexString(appTheme));
                expectEq(Integer.valueOf(android.R.style.Theme_Holo_Light), Integer.valueOf(
                        appRes[0].getIdentifier("android:style/Theme.Holo.Light", null, null)));

                Object theme = createTheme.invoke(app[0]);
                try {
                    applyThemeStyle.invoke(am2 ? am : null, theme, appTheme, true);
                    TypedValue v = new TypedValue();
                    // Set by the app style.
                    expect(lookup.found(theme, android.R.attr.windowNoTitle, v), "windowNoTitle");
                    expectEq(Integer.valueOf(TypedValue.TYPE_INT_BOOLEAN), Integer.valueOf(v.type));
                    expect(v.data != 0, "windowNoTitle false");
                    expect(lookup.found(theme, android.R.attr.colorForeground, v), "colorForeground");
                    expectEq(Integer.valueOf(0xff3ddc84), Integer.valueOf(v.data));
                    // Theme.Holo.Light: @android:color/background_holo_light.
                    expect(lookup.found(theme, android.R.attr.colorBackground, v), "colorBackground");
                    expectEq(Integer.valueOf(0xfff3f3f3), Integer.valueOf(v.data));
                    // Theme (root of the chain): 0.6.
                    expect(lookup.found(theme, android.R.attr.backgroundDimAmount, v), "backgroundDimAmount");
                    expectEq(Integer.valueOf(TypedValue.TYPE_FLOAT), Integer.valueOf(v.type));
                    expectEq(Float.valueOf(0.6f), Float.valueOf(v.getFloat()));
                } finally {
                    releaseTheme.invoke(app[0], theme);
                }
            }
        });

        // javac inlines R constants, so these read the classes through
        // reflection: they must be in framework.jar, and every id there
        // must name the same resource in framework-res.apk.
        check("com.android.internal.R: every id names its resource", new Check() {
            public void run() throws Exception {
                Resources sys = Resources.getSystem();
                int n = 0;
                for (Class<?> c : com.android.internal.R.class.getDeclaredClasses()) {
                    String type = c.getSimpleName();
                    if (type.equals("styleable")) continue;
                    for (Field f : c.getFields()) {
                        // Field names have '_' for '.'; aapt puts the attrs that
                        // public.xml does not declare in a type of their own.
                        String name = sys.getResourceName(f.getInt(null))
                                .replace('.', '_').replace("^attr-private/", "attr/");
                        expectEq("android:" + type + "/" + f.getName(), name);
                        n++;
                    }
                }
                // Resources outside R.styleable: 3503 in 4.4.4, 4515 in 6.0.1,
                // 5248 in 8.1.0, 5975 in 10; more when framework-res 6.0.1 is numbered as
                // the 6.0 image's (topic userspace: every resource is declared
                // public then).
                if (!SDK27 && pinnedIds()) {
                    expect(n > 4515, "pinned framework-res: " + n + " resources");
                } else {
                    expectEq(Integer.valueOf(SDK29 ? 5975 : SDK27 ? 5248 : SDK23 ? 4515 : 3503),
                             Integer.valueOf(n));
                }
            }
        });

        check("android.R: public ids, same as com.android.internal.R", new Check() {
            public void run() throws Exception {
                int n = 0;
                for (Class<?> c : android.R.class.getDeclaredClasses()) {
                    if (c.getSimpleName().equals("styleable")) continue;
                    Class<?> internal = Class.forName("com.android.internal.R$" + c.getSimpleName());
                    for (Field f : c.getFields()) {
                        expectEq(Integer.valueOf(internal.getField(f.getName()).getInt(null)),
                                 Integer.valueOf(f.getInt(null)));
                        n++;
                    }
                }
                // res/values/public.xml declares 1833 (4.4.4), 2335 (6.0.1),
                // 2476 (8.1.0), 2563 (10).
                if (!SDK27 && pinnedIds()) {
                    expect(n > 2335, "pinned framework-res: " + n + " public");
                } else {
                    expectEq(Integer.valueOf(SDK29 ? 2563 : SDK27 ? 2476 : SDK23 ? 2335 : 1833),
                             Integer.valueOf(n));
                }
                expect(android.R.class.getDeclaredClasses().length > 10, "android.R classes");
            }
        });

        check("com.android.internal.R.styleable: View attrs", new Check() {
            public void run() throws Exception {
                // The int[] arrays are not constants: a real field read.
                int[] view = com.android.internal.R.styleable.View;
                int background = com.android.internal.R.styleable.View_background;
                expectEq(Integer.valueOf(android.R.attr.background), Integer.valueOf(view[background]));
                expectEq(Integer.valueOf(android.R.attr.id),
                         Integer.valueOf(view[com.android.internal.R.styleable.View_id]));
                expectEq("android:attr/background",
                         Resources.getSystem().getResourceName(view[background]));
            }
        });

        long ms = (System.nanoTime() - start) / 1000000;
        System.out.println("FrameworkResTest: " + passed + " passed, " + failed + " failed (" + ms + " ms)");
        System.exit(failed);
    }
}
